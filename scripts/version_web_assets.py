"""Version first-party asset URLs as one module graph; --patch emits an apply_patch patch."""
from pathlib import Path
import argparse
import difflib
import hashlib
import json
import re

WEB = Path(__file__).resolve().parents[1] / 'web'
URL = re.compile(r'''(\./(?:[A-Za-z0-9_-]+/)*[A-Za-z0-9_.-]+\.(?:m?js|css|svg))(?:\?v=[a-f0-9]+)?(?=["'])''')
STATIC_IMPORT = re.compile(r'''^import\s*(?:[^;\n]*?\s+from\s*)?["'](\./[^"']+)["']''', re.MULTILINE)
PRELOAD_START = '    <!-- Startup modules: generated by scripts/version_web_assets.py -->'
PRELOAD_END = '    <!-- End startup modules -->'
SCOPED_APPS = ('free-study', 'math-courses')
WORKER_ASSETS_START = '// Public assets: generated by scripts/version_web_assets.py'
WORKER_ASSETS_END = '// End public assets'


def startup_modules(sources):
    """Only the eagerly used graph; dynamic chat/diagram engines stay lazy."""
    pending = ['app.js', 'portal.js', 'pwa.js']
    found = set()
    while pending:
        name = pending.pop()
        if name in found:
            continue
        found.add(name)
        # Stable vendor entrypoints are versioned; their content-hashed chunks
        # keep their own URLs and must not receive our query suffix twice.
        if name.startswith('vendor/'):
            continue
        text = sources[WEB / name]
        pending.extend(match.split('?')[0][2:] for match in STATIC_IMPORT.findall(text))
    return sorted(found)


def with_startup_preloads(sources):
    index = WEB / 'index.html'
    block = '\n'.join([PRELOAD_START, *(f'    <link rel="modulepreload" href="./{name}">'
                        for name in startup_modules(sources)), PRELOAD_END])
    text = sources[index]
    if PRELOAD_START in text:
        before, rest = text.split(PRELOAD_START, 1)
        _, after = rest.split(PRELOAD_END, 1)
        sources[index] = before + block + after
    else:
        marker = '    <script type="module" src="./app.js"></script>'
        if marker not in text:
            raise ValueError('Missing app entrypoint')
        sources[index] = text.replace(marker, marker + '\n' + block)
    return sources


def scoped_pages(sources):
    """Keep one HTML source for each shared page and materialize the scoped entries."""
    warning = '<!-- Generated by scripts/version_web_assets.py -->\n'
    for app in SCOPED_APPS:
        directory = WEB / f'pwa-{app}'
        manifest = json.loads((directory / 'manifest.webmanifest').read_text(encoding='utf-8'))
        name = manifest['short_name']
        for template, filename in (('index.html', 'index.html'), ('download.html', 'install.html')):
            page = sources[WEB / template].replace('="./', '="../')
            page = page.replace('href="../manifest.webmanifest"', 'href="./manifest.webmanifest"')
            page = page.replace('<html lang="zh-CN">', f'<html lang="zh-CN" data-pwa-app="{app}">')
            if filename == 'index.html':
                page = page.replace('content="GraspMemoEdu">', f'content="{name}">')
                page = page.replace('href="../download.html"', 'href="./install.html"')
            else:
                page = page.replace('在 iPhone、安卓手机或 Windows 上安装 GraspMemoEdu。阅读、练习与复习，继续使用同一账号的学习进度。',
                                    f'从桌面打开{name}。应用只恢复其范围内的页面，离开该范围后重新打开会回到{name}首页。')
                page = page.replace('href="../"', 'href="./"').replace('安装 GraspMemoEdu', f'安装{name}')
                page = page.replace(' GraspMemoEdu 图标', f'{name}图标')
                page = page.replace('把学习放到桌面。', f'安装{name}')
                page = re.sub(r'    <!-- Scoped install links -->.*?<!-- End scoped install links -->\n', '', page, flags=re.S)
            yield directory / filename, page.replace('<!doctype html>\n', '<!doctype html>\n' + warning, 1)


def worker_assets(text, generated=''):
    before, rest = text.split(WORKER_ASSETS_START, 1)
    _, after = rest.split(WORKER_ASSETS_END, 1)
    return before + WORKER_ASSETS_START + '\n' + generated + WORKER_ASSETS_END + after


def with_worker_assets(sources, version):
    worker = WEB / 'sw.js'
    # Only versioned script/style/image references from the published shell.
    paths = {url[2:] for text in sources.values() for url in URL.findall(text)}
    hashes = {}
    for name in sorted(paths - {'sw.js'}):
        path = WEB / name
        if path not in sources and not (name.startswith('vendor/') and path.is_file()):
            continue
        text = sources[path] if path in sources else path.read_text(encoding='utf-8')
        hashes[name] = hashlib.sha256(text.encode('utf-8')).hexdigest()
    generated = f'const ASSET_VERSION = {json.dumps(version)};\n'
    generated += f'const STATIC_ASSETS = {json.dumps(hashes, indent=2)};\n'
    sources[worker] = worker_assets(sources[worker], generated)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--patch', action='store_true')
    args = parser.parse_args()
    originals = {p: p.read_text(encoding='utf-8') for p in sorted(WEB.iterdir())
                 if p.suffix in {'.html', '.js', '.css', '.svg'}}
    canonical = with_startup_preloads({p: URL.sub(r'\1', text) for p, text in originals.items()})
    worker = WEB / 'sw.js'
    canonical[worker] = worker_assets(canonical[worker])
    digest = hashlib.sha256()
    for p, text in canonical.items():
        digest.update(p.name.encode() + b'\0' + text.encode() + b'\0')
    manifests = [WEB / 'manifest.webmanifest', *(WEB / f'pwa-{app}/manifest.webmanifest' for app in SCOPED_APPS)]
    for p in manifests:
        digest.update(p.relative_to(WEB).as_posix().encode() + b'\0' + p.read_text(encoding='utf-8').encode() + b'\0')
    # Vendor chunks carry content hashes in their names; version the stable
    # entrypoint URLs when the pinned dependency build changes as well.
    for p in sorted((WEB / 'vendor').rglob('*')):
        if p.is_file() and not p.is_relative_to(WEB / 'vendor/knowledge-clipper'):
            digest.update(p.relative_to(WEB).as_posix().encode() + b'\0' + p.read_bytes() + b'\0')
    digest.update((WEB.parent / 'scripts/clipper-assets.json').read_bytes().replace(b'\r\n', b'\n'))
    version = digest.hexdigest()[:16]
    changed = {p: URL.sub(lambda m: m[1] + '?v=' + version, text)
               for p, text in canonical.items()}
    with_worker_assets(changed, version)
    for p, text in scoped_pages(changed):
        changed[p] = text
        originals[p] = p.read_text(encoding='utf-8') if p.exists() else None
    changed = {p: text for p, text in changed.items() if text != originals[p]}
    if args.patch:
        print('*** Begin Patch')
        for p, text in changed.items():
            if originals[p] is None:
                print('*** Add File: ' + p.as_posix())
                for line in text.splitlines():
                    print('+' + line)
                continue
            print('*** Update File: ' + p.as_posix())
            diff = list(difflib.unified_diff(originals[p].splitlines(), text.splitlines(), lineterm=''))
            for line in diff[2:]:
                print('@@' if line.startswith('@@') else line)
        print('*** End Patch')
    elif changed:
        raise SystemExit('Static asset versions are stale. Apply the patch from scripts/version_web_assets.py --patch before export.')
    else:
        print('PASS static asset version ' + version)


if __name__ == '__main__':
    main()
